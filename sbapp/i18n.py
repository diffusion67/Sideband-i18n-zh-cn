_PROPERTY_RE = re.compile(
    r'^(?P<prefix>\s*(?:text|hint_text|helper_text|title)\s*:\s*)(?P<quote>["\'])(?P<value>.*)(?P=quote)(?P<suffix>[ \t]*(?:#.*)?)$',
    re.MULTILINE,
)


def translate(text):
    """Return the Chinese translation of an exact interface phrase when known."""
    return ZH_CN.get(text, text)


def localize_kv(layout):
    """Translate literal text properties in a Kivy layout without changing its structure."""
    def replace(match):
        value = match.group("value")
        translated = translate(value)
        return match.group("prefix") + match.group("quote") + translated + match.group("quote") + match.group("suffix")

    return _PROPERTY_RE.sub(replace, layout)
